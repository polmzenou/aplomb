export const propertyTypes: PropertyType[] = ["villa", "house", "loft", "apartment"];

export function getProperty(slug: string) {
  return properties.find((p) => p.slug === slug);
}

export const featuredProperties = properties.filter((p) => p.featured);

export function similarProperties(slug: string, count = 3) {
  const current = getProperty(slug);
  if (!current) return [];
  return properties
    .filter((p) => p.slug !== slug && p.status !== "sold")
    .sort((a, b) => Number(b.type === current.type) - Number(a.type === current.type) || Math.abs(a.price - current.price) - Math.abs(b.price - current.price))
    .slice(0, count);
}

export function roomArea(r: { w: number; h: number }) {
  return r.w * r.h;
}
